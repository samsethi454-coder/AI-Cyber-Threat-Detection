# 5. INTERACTIVE TRAFFIC ANALYSIS
# --------------------------------------------------

st.subheader("Analyze a Network Traffic Example")

st.write(
    "Adjust the example traffic features and ask the model "
    "to classify the record."
)

with st.form("traffic_form"):

    c1, c2 = st.columns(2)

    with c1:
        flow_duration = st.slider(
            "Flow duration",
            min_value=0.1,
            max_value=10.0,
            value=2.0,
            step=0.1,
        )

        total_fwd_packets = st.slider(
            "Forward packets",
            min_value=1,
            max_value=300,
            value=30,
        )

        total_bwd_packets = st.slider(
            "Backward packets",
            min_value=1,
            max_value=200,
            value=40,
        )

    with c2:
        flow_bytes_per_sec = st.slider(
            "Flow bytes per second",
            min_value=100,
            max_value=20000,
            value=5000,
            step=100,
        )

        packet_length_mean = st.slider(
            "Mean packet length",
            min_value=40,
            max_value=1500,
            value=500,
            step=10,
        )

    submitted = st.form_submit_button(
        "Analyze Traffic",
        type="primary",
    )

if submitted:

    sample = pd.DataFrame([{
        "flow_duration": flow_duration,
        "total_fwd_packets": total_fwd_packets,
        "total_bwd_packets": total_bwd_packets,
        "flow_bytes_per_sec": flow_bytes_per_sec,
        "packet_length_mean": packet_length_mean,
    }])

    prediction = model.predict(sample)[0]
    probabilities = model.predict_proba(sample)[0]

    attack_index = list(model.classes_).index("ATTACK")
    attack_probability = probabilities[attack_index]

    st.divider()
    st.subheader("Analysis Result")

    if prediction == "ATTACK":
        st.error("⚠️ Model classification: ATTACK")
    else:
        st.success("✅ Model classification: BENIGN")

    st.metric(
        "Model-estimated ATTACK probability",
        f"{attack_probability:.1%}",
    )

    st.write("**Submitted traffic features**")
    st.dataframe(sample, use_container_width=True)

    st.warning(
        "This prediction is generated from a model trained on "
        "synthetic data. It is a software demonstration, not a "
        "reliable assessment of real network traffic. The displayed "
        "probability is not a calibrated real-world risk score."
    )

